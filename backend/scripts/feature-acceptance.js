// Disposable data only, against the existing isolated local QA database.
require('dotenv').config({ quiet: true });
process.env.FIREBASE_ENABLED = 'false'; // Automated QA never sends real notifications.
const assert = require('node:assert/strict');
const database = new URL(process.env.DATABASE_URL);
if (process.env.NODE_ENV === 'production' || database.hostname !== '127.0.0.1' || database.port !== '3307' || database.pathname !== '/smart_sports_hub_demo') throw new Error('Requires isolated local demo database');
const request = require('supertest');
const jwt = require('jsonwebtoken');
const prisma = require('../src/lib/prisma');
const providerSessions = new Map();
require('../src/lib/stripe').getStripe = () => ({ checkout: { sessions: { retrieve: async id => providerSessions.get(id) } } });
const app = require('../src/app');
const { expireReservations } = require('../src/lib/reservation-lifecycle');
const { settle } = require('../src/controllers/checkout.controller');
const { annualEnd } = require('../src/lib/membership');
const users = [];
let sport, venue, card;
const prefix = `feature-${Date.now()}`;
const api = (user, method, path, data) => request(app)[method]('/api' + path).set('Authorization', `Bearer ${jwt.sign({ id: user.id }, process.env.JWT_SECRET)}`).send(data);
async function expect(user, method, path, data, status = 200) {
  const r = await api(user, method, path, data);
  assert.equal(r.status, status, `${path}: ${JSON.stringify(r.body)}`);
  return r.body;
}
async function main() {
  for (let i = 0; i < 3; i++) users.push(await prisma.user.create({ data: { name: prefix, email: `${prefix}-${i}@example.test`, password: 'not-used', role: i ? 'CUSTOMER' : 'ADMIN' } }));
  const [admin, customer, other] = users;
  const buy = tier => expect(customer, 'post', '/membership/purchase', { tier }, 201).then(r => r.data);
  const cash = paymentId => expect(admin, 'post', '/payments/confirm', { paymentId, receivedInPerson: true });
  card = await buy('SILVER');
  assert.equal(card.isActive, false);
  assert.equal(card.amount, 1000);
  assert.equal((await buy('SILVER')).paymentId, card.paymentId);
  await expect(customer, 'post', '/membership/purchase', { tier: 'GOLD' }, 409);
  await cash(card.paymentId);
  let current = (await expect(customer, 'get', '/membership/my')).data;
  assert.equal(current.tier, 'SILVER'); assert.equal(current.status, 'ACTIVE');
  assert.equal(new Date(current.endDate).toISOString(), annualEnd(new Date(current.startDate)).toISOString());
  const expiry = current.endDate;
  const attempts = await Promise.all([buy('SILVER'), buy('SILVER')]);
  assert.equal(attempts[0].paymentId, attempts[1].paymentId);
  await cash(attempts[0].paymentId);
  current = (await expect(customer, 'get', '/membership/my')).data;
  assert.equal(current.cardNumber, card.cardNumber);
  assert.equal(current.endDate, annualEnd(new Date(expiry)).toISOString());
  assert.equal(current.history.length, 2);
  console.log('PASS purchase, concurrent retry, annual expiry, renewal and stable card history');
  const upgrade = await buy('GOLD');
  assert.equal((await expect(customer, 'get', '/membership/my')).data.tier, 'SILVER');
  const session = { metadata: { paymentId: String(upgrade.paymentId) }, payment_status: 'paid', amount_total: 250000, currency: 'pkr', payment_intent: `${prefix}-intent` };
  await prisma.payment.update({ where: { id: upgrade.paymentId }, data: { stripeCheckoutSessionId: `cs_${prefix}` } });
  providerSessions.set(`cs_${prefix}`, session);
  await expect(customer, 'post', `/payments/${upgrade.paymentId}/reconcile`, {}, 403);
  await expect(admin, 'post', `/payments/${upgrade.paymentId}/reconcile`, {});
  await settle(session);
  current = (await expect(customer, 'get', '/membership/my')).data;
  assert.equal(current.tier, 'GOLD'); assert.equal(current.history.length, 3);
  assert.equal(await prisma.notification.count({ where: { userId: customer.id, title: 'Payment received' } }), 1);
  await expect(customer, 'post', '/membership/purchase', { tier: 'SILVER' }, 409);
  await prisma.membership.update({ where: { id: card.id }, data: { endDate: new Date(Date.now() - 1000) } });
  assert.equal((await expect(customer, 'get', '/membership/my')).data.status, 'EXPIRED');
  const expiredRenewal = await buy('GOLD');
  await prisma.payment.update({ where: { id: expiredRenewal.paymentId }, data: { expiresAt: new Date(Date.now() - 1000) } });
  await expireReservations();
  await expect(admin, 'post', '/payments/confirm', { paymentId: expiredRenewal.paymentId, receivedInPerson: true }, 409);
  assert.equal((await prisma.membershipChange.findUnique({ where: { paymentId: expiredRenewal.paymentId } })).status, 'EXPIRED');
  const basic = await buy('BASIC'); assert.equal(basic.isActive, true); assert.equal(basic.cardNumber, card.cardNumber);
  console.log('PASS paid upgrade, webhook idempotence, downgrade safeguard, expiry and retry');
  sport = await prisma.sport.create({ data: { name: prefix } });
  venue = await prisma.venue.create({ data: { name: prefix, sportId: sport.id } });
  const slot = await prisma.bookingSlot.create({ data: { venueId: venue.id, date: new Date(), startTime: '10:00', endTime: '11:00' } });
  const booking = await prisma.booking.create({ data: { userId: customer.id, slotId: slot.id, status: 'CONFIRMED' } });
  const review = { bookingId: booking.id, rating: 5, comment: 'Attended and enjoyed the venue' };
  await expect(customer, 'post', `/venues/${venue.id}/reviews`, review, 403);
  await prisma.booking.update({ where: { id: booking.id }, data: { status: 'SCANNED' } });
  await expect(other, 'post', `/venues/${venue.id}/reviews`, review, 403);
  const created = (await expect(customer, 'post', `/reviews/${venue.id}`, review, 201)).data;
  await expect(customer, 'post', `/venues/${venue.id}/reviews`, { ...review, rating: 4 }, 201);
  assert.equal(await prisma.review.count({ where: { userId: customer.id } }), 1);
  await expect(other, 'delete', `/reviews/${created.id}`, {}, 403);
  await expect(admin, 'delete', `/reviews/${created.id}`);
  console.log('PASS checked-in review eligibility, both routes, ownership, update and moderation');
  const complaint = (await expect(customer, 'post', '/complaints', { title: 'Facilities', description: 'Please check the lighting' }, 201)).data;
  await expect(other, 'patch', `/complaints/${complaint.id}`, { status: 'RESOLVED' }, 403);
  await expect(admin, 'patch', `/complaints/${complaint.id}`, { status: 'IN_PROGRESS', adminNote: 'Inspecting' });
  const before = await prisma.notification.count({ where: { userId: customer.id, type: 'COMPLAINT' } });
  await expect(admin, 'patch', `/complaints/${complaint.id}`, { adminNote: 'Lighting repaired' });
  assert.equal(await prisma.notification.count({ where: { userId: customer.id, type: 'COMPLAINT' } }), before + 1);
  await expect(admin, 'patch', `/complaints/${complaint.id}`, { status: 'INVALID' }, 400);
  assert.equal((await expect(other, 'get', '/complaints/my')).data.length, 0);
  console.log('PASS complaint admin response, response-only notification, validation and privacy');
  const notification = await prisma.notification.create({ data: { userId: other.id, title: 'Private', body: 'Other customer' } });
  await expect(customer, 'patch', '/notifications/read', { notificationIds: [notification.id] });
  assert.equal((await prisma.notification.findUnique({ where: { id: notification.id } })).isRead, false);
  const inbox = await expect(customer, 'get', '/notifications?limit=100');
  assert(inbox.unreadCount > 0); assert(inbox.data.every(n => n.userId === customer.id));
  await expect(customer, 'patch', '/notifications/read', { notificationIds: 'all' }, 400);
  await expect(customer, 'patch', '/notifications/read', {});
  assert.equal((await expect(customer, 'get', '/notifications')).unreadCount, 0);
  await expect(customer, 'get', '/notifications?limit=-1', undefined, 400);
  await expect(customer, 'get', '/notifications?page=0', undefined, 400);
  await expect(customer, 'post', '/notifications/fcm-token', { fcmToken: 'qa-token' });
  await expect(customer, 'post', '/notifications/fcm-token', { fcmToken: null });
  console.log('PASS notification delivery/read ownership, pagination validation and token registration');
  const invoice = (await expect(customer, 'get', `/payments/${card.paymentId}/invoice`)).data;
  assert.equal(invoice.status, 'PAID'); assert.equal(invoice.amount, 1000); assert.deepEqual(invoice.refunds, []);
  await expect(other, 'get', `/payments/${card.paymentId}/invoice`, undefined, 403);
  console.log('PASS paid invoice accuracy and owner access');
  console.log('6 feature acceptance groups passed. MySQL used; provider settlement simulated; no live push sent.');
}
async function cleanup() {
  const ids = users.map(u => u.id);
  await prisma.review.deleteMany({ where: { userId: { in: ids } } });
  await prisma.membershipChange.deleteMany({ where: { membership: { userId: { in: ids } } } });
  await prisma.refund.deleteMany({ where: { payment: { userId: { in: ids } } } });
  await prisma.payment.deleteMany({ where: { userId: { in: ids } } });
  await prisma.membership.deleteMany({ where: { userId: { in: ids } } });
  await prisma.booking.deleteMany({ where: { userId: { in: ids } } });
  if (venue) { await prisma.bookingSlot.deleteMany({ where: { venueId: venue.id } }); await prisma.venue.delete({ where: { id: venue.id } }); }
  if (sport) await prisma.sport.delete({ where: { id: sport.id } });
  await prisma.complaint.deleteMany({ where: { userId: { in: ids } } });
  await prisma.notification.deleteMany({ where: { userId: { in: ids } } });
  await prisma.user.deleteMany({ where: { id: { in: ids } } });
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { try { await cleanup(); } finally { await prisma.$disconnect(); } });
