require('dotenv').config({ quiet: true });
process.env.FIREBASE_ENABLED = 'false';
const assert = require('node:assert/strict');
const database = new URL(process.env.DATABASE_URL);
if (process.env.NODE_ENV === 'production' || database.hostname !== '127.0.0.1' || database.port !== '3307' || database.pathname !== '/smart_sports_hub_demo') throw new Error('Requires isolated local demo database');
const request = require('supertest');
const jwt = require('jsonwebtoken');
const prisma = require('../src/lib/prisma');
const { expireReservations, finishRefund } = require('../src/lib/reservation-lifecycle');
const { settle } = require('../src/controllers/checkout.controller');
const app = require('../src/app');
const prefix = `agenda-${Date.now()}`;
const users = []; let sport, venue, equipment, promo;
const api = (u, method, path, body) => request(app)[method]('/api' + path).set('Authorization', 'Bearer ' + jwt.sign({ id: u.id }, process.env.JWT_SECRET)).send(body);
async function expect(u, method, path, body, status = 200) { const r = await api(u, method, path, body); assert.equal(r.status, status, `${path}: ${JSON.stringify(r.body)}`); return r.body.data; }
const date = days => new Date(Date.now() + 5 * 3600000 + days * 86400000).toISOString().slice(0, 10);
async function main() {
  for (let i = 0; i < 3; i++) users.push(await prisma.user.create({ data: { name: prefix, email: `${prefix}-${i}@example.test`, password: 'unused', role: i ? 'CUSTOMER' : 'ADMIN' } }));
  const [admin, customer, other] = users;
  sport = await prisma.sport.create({ data: { name: prefix } });
  venue = await prisma.venue.create({ data: { sportId: sport.id, name: prefix, pricePerSlot: 100, openingTime: '00:00', closingTime: '23:59' } });
  equipment = await expect(admin, 'post', '/equipment', { sportId: sport.id, venueId: venue.id, name: 'QA padel racket', brand: 'QA', material: 'Fibreglass', ballType: 'Venue-supplied padel ball', pricePerSlot: 25, quantity: 2 }, 201);
  const menu = await expect(customer, 'get', `/venues/${venue.id}`);
  assert.equal(menu.equipment[0].ballType, 'Venue-supplied padel ball');
  await expect(customer, 'post', '/equipment', { name: 'unauthorized', sportId: sport.id }, 403);
  await expect(customer, 'post', `/equipment/${equipment.id}/rent`, { quantity: 0, rentalDate: date(1) }, 400);
  const rentBody = { quantity: 2, rentalDate: date(1), returnDate: date(3) };
  const races = await Promise.all([api(customer, 'post', `/equipment/${equipment.id}/rent`, rentBody), api(other, 'post', `/equipment/${equipment.id}/rent`, rentBody)]);
  assert.deepEqual(races.map(r => r.status).sort(), [201, 409]);
  const rental = races.find(r => r.status === 201).body.data;
  const owner = rental.userId === customer.id ? customer : other;
  assert.equal(rental.totalPrice, 150); assert.equal(rental.status, 'PENDING_PAYMENT');
  await expect(other.id === owner.id ? customer : other, 'post', `/equipment/rentals/${rental.id}/cancel`, {}, 403);
  await prisma.payment.update({ where: { id: rental.paymentId }, data: { expiresAt: new Date(Date.now() - 1000) } });
  await expireReservations();
  assert.equal((await prisma.equipmentRental.findUnique({ where: { id: rental.id } })).status, 'CANCELLED');
  // Late online success refunds the payment without resurrecting its inventory hold.
  await settle({ payment_status: 'paid', metadata: { paymentId: String(rental.paymentId) }, amount_total: 15000, currency: 'pkr', payment_intent: `pi_${prefix}` });
  assert.equal((await prisma.equipmentRental.findUnique({ where: { id: rental.id } })).status, 'CANCELLED');
  assert.equal(await prisma.refund.count({ where: { paymentId: rental.paymentId } }), 1);
  const paidRental = await expect(customer, 'post', `/equipment/${equipment.id}/rent`, rentBody, 201);
  await expect(admin, 'post', '/payments/confirm', { paymentId: paidRental.paymentId, receivedInPerson: true });
  assert.equal((await prisma.equipmentRental.findUnique({ where: { id: paidRental.id } })).status, 'CONFIRMED');
  await expect(customer, 'post', `/equipment/rentals/${paidRental.id}/cancel`, {});
  const refund = await prisma.refund.findFirst({ where: { paymentId: paidRental.paymentId } });
  assert.equal(refund.amount, 150); await finishRefund(refund, prefix);
  // Staff return and damage inspection; damage removes units and repeat return is rejected.
  const collected = await expect(customer, 'post', `/equipment/${equipment.id}/rent`, { quantity: 2, rentalDate: date(0) }, 201);
  await expect(admin, 'post', '/payments/confirm', { paymentId: collected.paymentId, receivedInPerson: true });
  await expect(customer, 'post', `/equipment/rentals/${collected.id}/return`, {}, 403);
  await expect(admin, 'post', `/equipment/rentals/${collected.id}/return`, { damagedQuantity: 1 }, 400);
  await expect(admin, 'post', `/equipment/rentals/${collected.id}/return`, { damagedQuantity: 1, damageNotes: 'Cracked frame' });
  await expect(admin, 'post', `/equipment/rentals/${collected.id}/return`, {}, 409);
  assert.equal((await prisma.equipment.findUnique({ where: { id: equipment.id } })).quantity, 1);
  console.log('PASS venue menu, authorization, duration pricing, capacity race, expiry, late settlement, cash refund, return and damage');
  promo = await expect(admin, 'post', '/promo', { code: prefix.toUpperCase(), discountType: 'PERCENTAGE', discountValue: 20, perCustomerLimit: 1, maxUses: 10 }, 201);
  assert((await expect(customer, 'get', '/promo')).some(p => p.id === promo.id));
  await expect(admin, 'post', '/promo', { code: prefix + '-BAD', discountValue: 101 }, 400);
  const slots = [];
  for (let i = 0; i < 3; i++) slots.push(await prisma.bookingSlot.create({ data: { venueId: venue.id, date: new Date(date(2)), startTime: `${10 + i}:00`, endTime: `${11 + i}:00` } }));
  const booking = await expect(customer, 'post', '/bookings', { slotId: slots[0].id, promoCode: '  ' + promo.code.toLowerCase() + ' ' }, 201);
  assert.equal(booking.finalPrice, 80);
  await expect(customer, 'post', '/bookings', { slotId: slots[1].id, promoCode: promo.code }, 400);
  await expect(customer, 'put', `/bookings/${booking.id}/cancel`, {});
  assert.equal((await prisma.promoCode.findUnique({ where: { id: promo.id } })).usedCount, 0);
  const retry = await expect(customer, 'post', '/bookings', { slotId: slots[1].id, promoCode: promo.code }, 201);
  await prisma.payment.update({ where: { id: retry.paymentId }, data: { expiresAt: new Date(Date.now() - 1) } }); await expireReservations();
  assert.equal(await prisma.promoCodeUsage.count({ where: { promoCodeId: promo.id } }), 0);
  await expireReservations();
  assert.equal((await prisma.promoCode.findUnique({ where: { id: promo.id } })).usedCount, 0);
  const promoRaces = await Promise.all([api(customer, 'post', '/bookings', { slotId: slots[0].id, promoCode: promo.code }), api(customer, 'post', '/bookings', { slotId: slots[2].id, promoCode: promo.code })]);
  assert.deepEqual(promoRaces.map(r => r.status).sort(), [201, 400]);
  await expect(customer, 'put', `/bookings/${promoRaces.find(r => r.status === 201).body.data.id}/cancel`, {});
  await expect(admin, 'patch', `/promo/${promo.id}`, { discountType: 'FIXED', discountValue: 1000 });
  const freeBooking = await expect(customer, 'post', '/bookings', { slotId: slots[0].id, promoCode: promo.code }, 201);
  assert.equal(freeBooking.finalPrice, 0); assert.equal(freeBooking.promoDiscount, 100);
  await expect(customer, 'put', `/bookings/${freeBooking.id}/cancel`, {});
  const rec = await expect(customer, 'get', '/recommendations/slots');
  assert(rec.every(s => !s.isBooked && s.recommendationReason));
  await expect(admin, 'get', '/reports/revenue?from=2026-02-30', {}, 400);
  const report = await expect(admin, 'get', '/reports/revenue');
  assert.equal(report.totalRevenue, Math.round((report.grossRevenue - report.refundedAmount) * 100) / 100);
  await expect(customer, 'get', '/reports/revenue', {}, 403);
  console.log('PASS normalized promos, customer offer access, per-customer limit, cancellation and expiry reversal, recommendations and report totals');
}
async function cleanup() {
  const ids = users.map(u => u.id);
  const payments = await prisma.payment.findMany({ where: { userId: { in: ids } }, select: { id: true } });
  await prisma.refund.deleteMany({ where: { paymentId: { in: payments.map(p => p.id) } } });
  await prisma.payment.deleteMany({ where: { userId: { in: ids } } });
  await prisma.promoCodeUsage.deleteMany({ where: { userId: { in: ids } } });
  await prisma.booking.deleteMany({ where: { userId: { in: ids } } });
  await prisma.equipmentRental.deleteMany({ where: { userId: { in: ids } } });
  if (equipment) await prisma.equipment.delete({ where: { id: equipment.id } });
  if (promo) await prisma.promoCode.delete({ where: { id: promo.id } });
  if (venue) { await prisma.bookingSlot.deleteMany({ where: { venueId: venue.id } }); await prisma.venue.delete({ where: { id: venue.id } }); }
  if (sport) await prisma.sport.delete({ where: { id: sport.id } });
  await prisma.notification.deleteMany({ where: { userId: { in: ids } } });
  await prisma.user.deleteMany({ where: { id: { in: ids } } });
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { try { await cleanup(); } finally { await prisma.$disconnect(); } });
